#!/usr/bin/env python3
"""Official E1080008: 육우·거세·체중 전체·전국 only. Merge verified monthly records."""
import argparse,json,re,os,tempfile,urllib.parse,datetime
from pathlib import Path
from bs4 import BeautifulSoup
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
URL='https://mtrace.go.kr/statHtml/statHtml.do?orgId=323&tblId=DT_323903_E1080008&conn_path=I2'
FIELDS=['count','live','weight','fat','area','yield_index','marbling','price']
def parse_table(html):
 s=BeautifulSoup(html,'html.parser'); t=s.select_one('table#mainTable')
 if not t:raise ValueError('mainTable missing')
 heads=t.select('thead tr');months=[h.get('name')[1:5]+'-'+h.get('name')[5:] for h in heads[0].find_all('th') if re.fullmatch(r'M20\d{4}',h.get('name',''))]
 if not months:raise ValueError('month headers missing')
 # Each month has one 전국 block, followed by separate slaughterhouse-specific blocks.
 spans=[]
 for h in heads[1].find_all('th'):
  spans.append((h.get('title',''),int(h.get('colspan') or 1)))
 ptr=0;month_offsets=[]
 for month in months:
  begin=ptr;found=False
  while ptr<len(spans):
   label,width=spans[ptr];ptr+=1
   if label=='전국':
    month_offsets.append((month,begin));found=True
    break
   begin+=width
  if not found:raise ValueError('전국 헤더 누락 '+month)
  # skip remaining market headers until next month block; count each month group from 1st header
  total_span=int(next(h.get('colspan') for h in heads[0].find_all('th') if h.get('name')=='M'+month.replace('-','')))
  used=sum(w for _,w in spans[:ptr]);target=sum(int(h.get('colspan') or 0) for h in heads[0].find_all('th') if h.get('name','').startswith('M20') and h.get('name')<='M'+month.replace('-',''))
  # Months are descending, so use total span relative to consumed header groups.
  while ptr<len(spans) and sum(w for _,w in spans[:ptr])<sum(int(h.get('colspan') or 0) for h in heads[0].find_all('th') if h.get('name','').startswith('M20') and months.index(h.get('name')[1:5]+'-'+h.get('name')[5:])<=months.index(month)):
   ptr+=1
 row=None
 for tr in t.select('tbody tr'):
  cells=[c.get('title','').strip() for c in tr.find_all('td',recursive=False)]
  if len(cells)>3 and cells[:3]==['육우','거세','전체']:row=cells;break
 if row is None:raise ValueError('육우/거세/전체 행 없음')
 records={};position=0
 for month in months:
  values=row[3+position:3+position+8]
  if len(values)<8:break
  try:nums=[float(v.replace(',','')) for v in values]
  except ValueError:nums=[]
  if nums and 100<=nums[0]<=30000 and 200<=nums[2]<=700 and 0<=nums[6]<=9:
   rec={'month':month,'breed':'육우','sex':'거세우'}
   for key,val in zip(FIELDS,nums):rec[key]=int(val) if key=='count' else val
   records[month]=rec
  mhead=next(h for h in heads[0].find_all('th') if h.get('name')=='M'+month.replace('-',''))
  position+=int(mhead.get('colspan'))
 if not records:raise ValueError('검증된 전국 육우 거세우 자료 없음')
 return records
def collect_months():
 """Query all months from January 2026 through last complete month.

 Uses the *actual working* form submission generated by the public statistics page
 rather than hard-coding undocumented POST fields. Each month is separately checked.
 Current published months are retained if historical requests fail.
 """
 kst=datetime.timezone(datetime.timedelta(hours=9))
 now=datetime.datetime.now(kst)
 last=(now.year*12+now.month-2)
 wanted=[f'{n//12:04d}-{n%12+1:02d}' for n in range(2026*12,last+1)]
 found={}
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True,args=['--no-sandbox'])
  context=browser.new_context(locale='ko-KR',timezone_id='Asia/Seoul')
  page=context.new_page();captures=[]
  def capture(resp):
   if '/statHtml/html.do' not in resp.url or resp.request.method!='POST' or resp.status!=200:return
   try:
    obj=resp.json()
    if obj.get('result') and 'mainTable' in str(obj['result'][0]):captures.append((resp.request.post_data or '',obj['result'][0]))
   except Exception:pass
  page.on('response',capture)
  try:
   page.goto(URL,wait_until='domcontentloaded',timeout=45000)
   page.wait_for_timeout(8500)
   if not captures:
    try:
     page.get_by_text('통계표조회',exact=True).first.click(timeout=3000)
     page.wait_for_timeout(6500)
    except Exception:pass
   if not captures:raise RuntimeError('공식 통계표 초기 응답 없음')
   form,html=captures[-1]
   found.update(parse_table(html))
   print('기본 조회:',', '.join(sorted(found)))
   if not form:
    print('경고: 요청 양식 확인 불가, 과거 월 추가 조회 생략')
    return found
   pairs=urllib.parse.parse_qsl(form,keep_blank_values=True)
   if not any(k=='fieldList' for k,v in pairs):
    print('경고: 월 선택 조건 fieldList가 없어 과거 월 추가 조회 생략')
    return found
   base_fields=json.loads(next(v for k,v in pairs if k=='fieldList'))
   if not any(isinstance(x,dict) and x.get('targetId')=='PRD' for x in base_fields):
    print('경고: PRD 월 선택 필드가 없어 과거 월 추가 조회 생략')
    return found
   for month in wanted:
    if month in found:continue
    ym=month.replace('-','')
    fields=json.loads(json.dumps(base_fields,ensure_ascii=False))
    for entry in fields:
     if isinstance(entry,dict) and entry.get('targetId')=='PRD':
      entry['prdValue']='M,'+ym+',@'
      entry['targetValue']=''
    new_pairs=[];time_set=False
    for key,val in pairs:
     if key=='fieldList':val=json.dumps(fields,ensure_ascii=False,separators=(',',':'))
     elif key=='timeChkM':val=ym;time_set=True
     elif key=='reqCellCnt':val='200'
     new_pairs.append((key,val))
    if not time_set:new_pairs.append(('timeChkM',ym))
    try:
     response=context.request.post('https://mtrace.go.kr/statHtml/html.do',
      data=urllib.parse.urlencode(new_pairs),
      headers={'Content-Type':'application/x-www-form-urlencoded; charset=UTF-8',
               'Referer':URL,'X-Requested-With':'XMLHttpRequest'},timeout=25000)
     obj=response.json()
     if not response.ok or not obj.get('result'):raise ValueError('응답 비정상')
     rows=parse_table(obj['result'][0]);rec=rows.get(month)
     if not rec:raise ValueError('요청 월 행 없음')
     found[month]=rec
     print(month,'수집:',rec['count'],'두 / 도체중',rec['weight'],'kg')
    except Exception as ex:
     print('주의:',month,'조회 실패. 기존 저장값 유지:',str(ex)[:150])
   return found
  finally:browser.close()
AGE_TABLE='DT_323901_A300000005'
AGE_URL=f'https://mtrace.go.kr/statHtml/statHtml.do?orgId=323&tblId={AGE_TABLE}&conn_path=I2'
AGE_POST='https://mtrace.go.kr/statHtml/html.do'

def parse_age(html):
 """The official monthly table has TIME + 10 numeric cells; beef-steer is last."""
 soup=BeautifulSoup(html,'html.parser'); table=soup.select_one('table#mainTable')
 if not table:raise ValueError('평균도축개월령 mainTable 없음')
 headings=table.select('thead tr')
 if not headings or not any('육우' in h.get('title','') for h in headings[0].find_all('th')):
  raise ValueError('육우 항목 머리글 확인 실패')
 out={}
 for tr in table.select('tbody tr'):
  td=tr.find_all('td',recursive=False)
  if len(td)<11:continue
  date=td[0].get('title','').strip()
  m=re.fullmatch(r'(20\d{2})\.\s*(\d{1,2})',date)
  if not m:continue
  month=f'{m.group(1)}-{int(m.group(2)):02d}'
  raw=td[10].get('title','').replace(',','').strip()
  try:value=float(raw)
  except ValueError:continue
  if 10<=value<=150:out[month]=value
 return out

def age_form(months):
 """Official public table selection: breed Hanwoo+beef, all four sex groups."""
 fields=[{'targetId':'PRD','targetValue':'','prdValue':'M,'+','.join(reversed(months))+',@'},
         {'targetId':'ITM_ID','targetValue':'T001','prdValue':''}]
 for key,values in [('OV_L1_ID',['01','03']),('OV_L2_ID',['00','01','02','03'])]:
  fields += [{'targetId':key,'targetValue':v,'prdValue':''} for v in values]
 pairs=[('orgId','323'),('tblId',AGE_TABLE),('language','ko'),('file',''),('analText',''),('scrId',''),
 ('fieldList',json.dumps(fields,ensure_ascii=False,separators=(',',':'))),('colAxis','A,B'),('rowAxis','TIME'),
 ('isFirst','N'),('contextPath','/statHtml'),('connPath','I2'),('statId','2006901'),('viewKind','1'),
 ('mode','tab'),('dataOpt','ko'),('view','table'),('periodStr','M'),('findData','on'),
 ('classAllArr','[{"objVarId":"A","ovlSn":"1"},{"objVarId":"B","ovlSn":"2"}]'),
 ('classSet','[{"objVarId":"A","ovlSn":"1","visible":"true"},{"objVarId":"B","ovlSn":"2","visible":"true"}]'),
 ('itemMultiply','8'),('reqCellCnt',str(len(months)*8)),('enableLevelExpr','Y'),('prdSort','desc'),
 ('itemChkLi','T001'),('classChkLi1_1','01='),('classChkLi1_1','03=')]
 pairs += [('classChkLi2_1',v+'=') for v in ('00','01','02','03')]
 pairs += [('timeChkM',m) for m in reversed(months)]
 return pairs

def collect_ages():
 """Recheck Jan 2026 through previous calendar month, 3 months per call.
 Any missing/unpublished month stays absent. Old verified values survive failures.
 """
 kst=datetime.timezone(datetime.timedelta(hours=9));now=datetime.datetime.now(kst)
 last=now.year*12+now.month-2
 months=[f'{k//12:04d}-{k%12+1:02d}' for k in range(2026*12,last+1)]
 found={}
 if not months:return found
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True,args=['--no-sandbox'])
  try:
   ctx=browser.new_context(locale='ko-KR',timezone_id='Asia/Seoul')
   ctx.new_page().goto(AGE_URL,wait_until='domcontentloaded',timeout=45000)
   for i in range(0,len(months),3):
    chunk=months[i:i+3]; yms=[x.replace('-','') for x in chunk]
    try:
     resp=ctx.request.post(AGE_POST,data=urllib.parse.urlencode(age_form(yms)),
       headers={'Content-Type':'application/x-www-form-urlencoded; charset=UTF-8',
                'Referer':AGE_URL,'X-Requested-With':'XMLHttpRequest'},timeout=35000)
     if not resp.ok:raise RuntimeError(f'HTTP {resp.status}')
     raw=resp.json();results=raw.get('result',[])
     if not results:raise ValueError('result HTML 미제공')
     got=parse_age(results[0])
     for mo in chunk:
      if mo in got:found[mo]=got[mo]
     print('육우 거세우 도축개월령',','.join(chunk),'->',','.join(f'{m}:{found[m]}' for m in chunk if m in found) or '미수집')
    except Exception as ex:
     print('주의: 월령',','.join(chunk),'조회 실패, 저장된 과거 데이터 유지:',str(ex)[:160])
  finally:browser.close()
 return found

def main():
 arg=argparse.ArgumentParser();arg.add_argument('--html',help='공식 HTML 응답으로 오프라인 검증');args=arg.parse_args()
 newer=parse_table(Path(args.html).read_text('utf-8')) if args.html else collect_months()
 # Fetch each batch of historical age months, independent of national quality table.
 ages={}
 if not args.html:
  try:ages=collect_ages()
  except Exception as exc:print('주의: 월령 통합 조회 실패, 기존 월령 보존:',str(exc)[:180])
 for month,age in ages.items():
  if month in newer:newer[month]['age_months']=age
 file=ROOT/'beef_national_data.json';old={}
 if file.exists():
  try:old={r['month']:r for r in json.loads(file.read_text('utf-8')).get('records',[])}
  except Exception:pass
 for month,rec in newer.items():
  if 'age_months' not in rec and month in old and 'age_months' in old[month]:rec['age_months']=old[month]['age_months']
 old.update(newer)
 # Backfill age even when corresponding national quality month is already saved,
 # but skip creating partial quality records for months not yet collected.
 for month,age in ages.items():
  if month in old:old[month]['age_months']=age
 payload={'source_table':'DT_323903_E1080008','definition':'전국 육우 거세우, 체중간격 전체, 등급판정 항목별 평균','records':[old[k] for k in sorted(old)]}
 fd,tmp=tempfile.mkstemp(dir=ROOT,prefix='.beef_national_',suffix='.json')
 try:
  with os.fdopen(fd,'w',encoding='utf8') as f:json.dump(payload,f,ensure_ascii=False,indent=2)
  os.replace(tmp,file)
 finally:
  if os.path.exists(tmp):os.unlink(tmp)
 print('Verified beef steer national:', ', '.join(sorted(newer)))
 print('전체 보관 월:', ', '.join(sorted(old)))
if __name__=='__main__':main()
